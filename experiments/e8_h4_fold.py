"""ap. e8_h4_fold -- E8 built from a diagram, folded to H4, and the (7, 13) chain.

CC0. Co-authored. Stdlib only. Status: PROPOSED.

  1 E8        eight vectors alpha_i and phi * alpha_i (i = 1..4), where
              alpha_1..alpha_4 are simple roots of H4 (Gram 2 on the
              diagonal, -phi on the 5-edge, -1 on the 3-edges). With the
              integer form (x, y) = the rational part of <x, y> (the a of
              a + b*phi) their Gram matrix is computed, checked to be a
              simply-laced Cartan matrix whose diagram has one branch node
              with arms 1, 2, 4 and whose Coxeter number and exponents are
              those computed for E8 from its own diagram. The roots are
              then generated by reflections, in integers.
  2 fold      each root is a vector with a + b*phi coordinates on the
              alpha_i. Its squared length there is exact. Tested: two sets
              of 120, one phi times the other; each a 600-cell's vertices.
  3 plane     the roots on E8's Coxeter plane (h = 30): how many rings,
              how many roots on each.
  4 chain     the Coxeter element r_1 r_2 r_3 r_4 (each r_i the pair of E8
              reflections in alpha_i and phi*alpha_i) acts on the fold's
              4-space and on its conjugate 4-space. Its turns in each are
              computed from exact traces. Each of its orbits of roots is
              then read in both 4-spaces: do 4 consecutive points form a
              regular tetrahedron, with what edge over radius, beside the
              logged chains (1, 11) and (7, 13) at N = 30.

Exact a + b*phi forms for everything in item 2 and for the traces; floats
for the plane and the orbit geometry. Observer slots null.

  python3 experiments/e8_h4_fold.py [seed]
"""
import cmath
import itertools
import math
import sys
from fractions import Fraction
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import coxeter_exponents as X  # noqa: E402
import emlib  # noqa: E402
from exact import PHI, ZPhi, ZERO, ONE  # noqa: E402
from toolkit import primitives as P  # noqa: E402

NAME = "e8_h4_fold"
PHI_F = (1 + 5 ** 0.5) / 2
PHI_C = 1 - PHI_F                      # the conjugate, 1 - phi
ASKED = ("PROPOSED: E8's 240 roots fold to two 600-cells with radii in the ratio phi; on "
         "E8's Coxeter plane they fall on rings of 30; the (7, 13)/30 chain is E8's Coxeter "
         "element on the conjugate 4-space.")

H4_GRAM = [[ZPhi(2), -PHI, ZERO, ZERO],
           [-PHI, ZPhi(2), -ONE, ZERO],
           [ZERO, -ONE, ZPhi(2), -ONE],
           [ZERO, ZERO, -ONE, ZPhi(2)]]


def h4_form(x, y):
    out = ZERO
    for i in range(4):
        for j in range(4):
            if H4_GRAM[i][j]:
                out = out + x[i] * H4_GRAM[i][j] * y[j]
    return out


def basis():
    """alpha_1..alpha_4, then phi*alpha_1..phi*alpha_4, as a + b*phi coordinates."""
    e = [[ONE if i == j else ZERO for j in range(4)] for i in range(4)]
    return e + [[PHI if i == j else ZERO for j in range(4)] for i in range(4)]


def e8_gram():
    b = basis()
    return [[int(h4_form(u, v).a) for v in b] for u in b]


def diagram_shape(gram):
    n = len(gram)
    adj = {i: [j for j in range(n) if j != i and gram[i][j] == -1] for i in range(n)}
    deg = sorted(len(v) for v in adj.values())
    arms = None
    branch = [i for i in adj if len(adj[i]) == 3]
    if len(branch) == 1:
        arms = []
        for start in adj[branch[0]]:
            length, prev, cur = 1, branch[0], start
            while True:
                nxt = [j for j in adj[cur] if j != prev]
                if not nxt:
                    break
                prev, cur, length = cur, nxt[0], length + 1
            arms.append(length)
        arms.sort()
    return {"simply_laced_cartan": all(gram[i][i] == 2 for i in range(n))
            and all(gram[i][j] in (0, -1) for i in range(n) for j in range(n) if i != j),
            "n_edges": sum(len(v) for v in adj.values()) // 2, "degrees": deg,
            "branch_node_arms": arms,
            "edges": sorted((i, j) for i in adj for j in adj[i] if i < j)}


def roots(gram):
    n = len(gram)
    simple = [tuple(1 if i == j else 0 for j in range(n)) for i in range(n)]
    seen, frontier = set(simple), list(simple)
    while frontier:
        nxt = []
        for r in frontier:
            for i in range(n):
                c = sum(r[j] * gram[j][i] for j in range(n))
                if c:
                    s = list(r)
                    s[i] -= c
                    s = tuple(s)
                    if s not in seen:
                        seen.add(s)
                        nxt.append(s)
        frontier = nxt
    return sorted(seen)


def folded(root):
    """The root's a + b*phi coordinates on alpha_1..alpha_4."""
    return tuple(ZPhi(root[i], root[i + 4]) for i in range(4))


def cholesky(g):
    n = len(g)
    low = [[0.0] * n for _ in range(n)]
    for i in range(n):
        for j in range(i + 1):
            s = g[i][j] - sum(low[i][k] * low[j][k] for k in range(j))
            low[i][j] = math.sqrt(s) if i == j else s / low[j][j]
    return low


def embed(x, phi_value, low):
    """Euclidean coordinates of sum x_i alpha_i, with phi read as phi_value."""
    c = [float(v.a) + float(v.b) * phi_value for v in x]
    return [sum(c[i] * low[i][k] for i in range(4)) for k in range(4)]


def h4_reflect(x, i):
    """r_i on a + b*phi coordinates: x -> x - <x, alpha_i> alpha_i."""
    c = ZERO
    for j in range(4):
        if H4_GRAM[j][i]:
            c = c + x[j] * H4_GRAM[j][i]
    y = list(x)
    y[i] = y[i] - c
    return tuple(y)


def coxeter_h4(x):
    for i in (3, 2, 1, 0):
        x = h4_reflect(x, i)
    return x


def exponents_from_traces(traces, h):
    out = []
    for m in range(1, h):
        mult = sum(traces[j] * cmath.exp(-2j * math.pi * j * m / h) for j in range(h)) / h
        out += [m] * int(round(mult.real))
    return out


def verdict(orbit_rows, space, found_turns, want_turns, logged_edge):
    """The logged chain against the Coxeter element in one 4-space: the turns,
    and how many orbits of roots are that chain (regular tetrahedra in every
    window, with the logged edge over radius)."""
    regular = [o for o in orbit_rows if o[space]["regular_tetrahedra_in_every_window"]]
    same = [o for o in regular if abs(o[space]["edge_over_radius"] - logged_edge) < 1e-8]
    return {"turns_found": found_turns, "turns_of_the_logged_chain": want_turns,
            "turns_match": found_turns == want_turns,
            "orbits": len(orbit_rows), "orbits_that_are_regular_chains": len(regular),
            "orbits_that_are_the_logged_chain": len(same),
            "squared_lengths_of_those_orbits": sorted({o["squared_length"] for o in same}),
            "logged_edge_over_radius": logged_edge,
            "verdict": "match" if found_turns == want_turns and same else "no match",
            "verdict_means": "the turns are the logged chain's and at least one orbit of "
                             "roots is the logged chain; not every orbit is"}


def run(seed=0):
    gram = e8_gram()
    shape = diagram_shape(gram)
    edges = {e: 3 for e in shape["edges"]}
    c8 = X.coxeter_element(edges, 8)
    ident = [[1.0 if i == j else 0.0 for j in range(8)] for i in range(8)]
    tr, p, h = [8.0], ident, None
    for k in range(1, 100):
        p = X.matmul(p, c8)
        if max(abs(p[i][j] - ident[i][j]) for i in range(8) for j in range(8)) < 1e-8:
            h = k
            break
        tr.append(sum(p[i][i] for i in range(8)))
    exps = exponents_from_traces(tr, h)
    h_std, exps_std = X.exponents("E", 8)
    rs = roots(gram)

    # ---- 2 the fold, exact
    fold = {r: folded(r) for r in rs}
    norm = {r: h4_form(fold[r], fold[r]) for r in rs}
    values = sorted(set(norm.values()))
    groups = {v: [r for r in rs if norm[r] == v] for v in values}
    small_v, large_v = (values + [None, None])[:2]
    small = {fold[r] for r in groups.get(small_v, [])}
    large = {fold[r] for r in groups.get(large_v, [])}
    scaled = {tuple(c * PHI for c in x) for x in small}
    pts = sorted(small, key=lambda x: tuple((c.a, c.b) for c in x))
    ip = {}
    nbr_counts, top_values = [], set()
    for i, x in enumerate(pts):
        best, cnt = None, 0
        for j, y in enumerate(pts):
            if i == j:
                continue
            v = h4_form(x, y)
            ip[v] = ip.get(v, 0) + 1
            if best is None or v > best:
                best, cnt = v, 1
            elif v == best:
                cnt += 1
        nbr_counts.append(cnt)
        top_values.add(best)
    fold_part = {
        "n_roots": len(rs), "distinct_folded_points": len(set(fold.values())),
        "squared_lengths_exact": [v.pair() for v in values],
        "squared_lengths_text": [str(v) for v in values],
        "roots_per_squared_length": [len(groups[v]) for v in values],
        "two_sets_of_120": [len(groups[v]) for v in values] == [120, 120],
        "squared_length_ratio_is_phi_squared":
            len(values) == 2 and large_v == small_v * PHI * PHI,
        "radius_ratio": "phi (the squared lengths are in the ratio phi^2 = 1 + phi)"
        if len(values) == 2 and large_v == small_v * PHI * PHI else None,
        "larger_set_is_phi_times_the_smaller_exactly": scaled == large,
        "smaller_set": {
            "n_points": len(small),
            "closed_under_negation": all(tuple(-c for c in x) in small for x in small),
            "inner_products_exact": sorted(str(v) for v in ip),
            "n_distinct_inner_products": len(ip),
            "nearest_neighbours_per_point": sorted(set(nbr_counts)),
            "nearest_inner_product": [str(v) for v in top_values],
            "n_edges": sum(nbr_counts) // 2,
            "reads_as_600_cell_vertices":
                len(small) == 120 and set(nbr_counts) == {12} and sum(nbr_counts) // 2 == 720}}

    # ---- floats: the two 4-spaces and R^8
    g_par = [[float(v.a) + float(v.b) * PHI_F for v in row] for row in H4_GRAM]
    g_perp = [[float(v.a) + float(v.b) * PHI_C for v in row] for row in H4_GRAM]
    l_par, l_perp = cholesky(g_par), cholesky(g_perp)
    c_par, c_perp = 1.0 / (PHI_F * math.sqrt(5.0)), PHI_F / math.sqrt(5.0)

    def r8(x):
        return ([math.sqrt(c_par) * v for v in embed(x, PHI_F, l_par)]
                + [math.sqrt(c_perp) * v for v in embed(x, PHI_C, l_perp)])
    coords = {r: r8(fold[r]) for r in rs}
    e8_norms = sorted({round(P.dot(v, v), 9) for v in coords.values()})

    # ---- 3 E8's Coxeter plane
    b = basis()
    simple8 = [r8(tuple(v)) for v in b]
    plane = P.coxeter_plane(simple8, 30)
    radii = {}
    for r in rs:
        q = [P.dot(coords[r], u) for u in plane]
        radii.setdefault(round(math.hypot(*q), 6), []).append(r)
    rings = [{"radius": k, "n_roots": len(v)} for k, v in sorted(radii.items())]
    plane_part = {"h": 30, "n_rings": len(rings), "rings": rings,
                  "every_ring_has_30": all(x["n_roots"] == 30 for x in rings),
                  "radius_rounding": 1e-6}

    # ---- 4 the Coxeter element on the two 4-spaces
    cols = [coxeter_h4(tuple(ONE if i == j else ZERO for i in range(4))) for j in range(4)]
    mat = [[cols[j][i] for j in range(4)] for i in range(4)]        # exact, a + b*phi entries

    def mul(a, c):
        return [[sum((a[i][k] * c[k][j] for k in range(4)), ZERO) for j in range(4)]
                for i in range(4)]
    eye = [[ONE if i == j else ZERO for j in range(4)] for i in range(4)]
    pw, traces, order = eye, [], None
    for k in range(0, 61):
        if k and pw == eye:
            order = k
            break
        traces.append(sum((pw[i][i] for i in range(4)), ZERO))
        pw = mul(pw, mat)
    t_par = [float(t.a) + float(t.b) * PHI_F for t in traces]
    t_perp = [float(t.a) + float(t.b) * PHI_C for t in traces]
    ex_par = exponents_from_traces(t_par, order)
    ex_perp = exponents_from_traces(t_perp, order)

    orbits, left = [], set(rs)
    while left:
        r0 = min(left)
        orb, x = [], fold[r0]
        back = {v: k for k, v in fold.items()}
        for _ in range(order):
            orb.append(back[x])
            x = coxeter_h4(x)
        orbits.append(orb)
        left -= set(orb)

    def chain_reading(points):
        n = len(points)
        worst = 0.0
        for k in range(n):
            idx = [(k + j) % n for j in range(4)]
            d = [math.dist(points[a], points[c]) for a, c in itertools.combinations(idx, 2)]
            worst = max(worst, (max(d) - min(d)) / min(d))
        rad = P.norm(points[0])
        return {"regular_tetrahedra_in_every_window": worst < 1e-9,
                "largest_relative_edge_spread": worst,
                "edge_over_radius": math.dist(points[0], points[1]) / rad}
    orbit_rows = []
    for orb in orbits:
        par = [embed(fold[r], PHI_F, l_par) for r in orb]
        perp = [embed(fold[r], PHI_C, l_perp) for r in orb]
        orbit_rows.append({"n": len(orb), "squared_length": str(norm[orb[0]]),
                           "fold_space": chain_reading(par),
                           "conjugate_space": chain_reading(perp)})
    logged = emlib.load_run(emlib.RUNS / "corkscrew_seed0.json")["outputs"]["tetrahedra_chain"]["r4"]
    ring = {(c["p"], c["q"]): c["edge_over_radius"] for c in logged["closed_chains"]
            if c["n_tetrahedra_to_close"] == 30}

    def turns(ex):
        return sorted(m for m in ex if 2 * m < order)
    eor_par = sorted({round(o["fold_space"]["edge_over_radius"], 9) for o in orbit_rows})
    eor_perp = sorted({round(o["conjugate_space"]["edge_over_radius"], 9) for o in orbit_rows})
    chain_part = {
        "coxeter_element": "r_1 r_2 r_3 r_4, each r_i = the E8 reflections in alpha_i and "
                           "phi*alpha_i",
        "order": order, "traces_exact": [t.pair() for t in traces],
        "exponents_on_the_fold_space": ex_par,
        "exponents_on_the_conjugate_space": ex_perp,
        "together": sorted(ex_par + ex_perp),
        "together_equal_e8_exponents": sorted(ex_par + ex_perp) == exps,
        "turns_fold_space": turns(ex_par), "turns_conjugate_space": turns(ex_perp),
        "n_orbits_of_roots": len(orbits), "orbit_sizes": sorted({len(o) for o in orbits}),
        "orbits": orbit_rows,
        "every_orbit_regular_in_fold_space":
            all(o["fold_space"]["regular_tetrahedra_in_every_window"] for o in orbit_rows),
        "every_orbit_regular_in_conjugate_space":
            all(o["conjugate_space"]["regular_tetrahedra_in_every_window"] for o in orbit_rows),
        "edge_over_radius_fold_space": eor_par,
        "edge_over_radius_conjugate_space": eor_perp,
        "logged_chains_at_30": {f"({p}, {q})": v for (p, q), v in ring.items()},
        "chain_1_11": verdict(orbit_rows, "fold_space", turns(ex_par), [1, 11], ring[(1, 11)]),
        "chain_7_13": verdict(orbit_rows, "conjugate_space", turns(ex_perp), [7, 13],
                              ring[(7, 13)])}

    return {"asked": ASKED,
            "bound": {"seed": seed, "exact": "the Gram matrix, the roots, the fold, the "
                      "squared lengths, the 600-cell reading and the traces",
                      "floats": "Coxeter number and exponents of the 8x8 element, the plane, "
                                "the orbit geometry (tolerance 1e-9, radii rounded to 1e-6)",
                      "h4_gram": "2 on the diagonal, -phi on the 5-edge, -1 on the 3-edges",
                      "integer_form": "(x, y) = the a of <x, y> = a + b*phi",
                      "one_coxeter_element": "one ordering of the reflections; all orderings "
                                             "are conjugate, not all were run"},
            "e8": {"gram": gram, "diagram": shape,
                   "is_e8_shape": shape["simply_laced_cartan"] and shape["n_edges"] == 7
                   and shape["branch_node_arms"] == [1, 2, 4],
                   "coxeter_number": h, "exponents": exps,
                   "computed_from_the_standard_e8_diagram": {"h": h_std, "exponents": exps_std},
                   "same_h_and_exponents": (h, exps) == (h_std, exps_std),
                   "n_roots": len(rs),
                   "squared_lengths_in_r8": e8_norms},
            "fold": fold_part, "coxeter_plane": plane_part, "chain": chain_part}


def main(argv):
    seed = int(argv[0]) if argv else 0  # deterministic; seed kept for the schema
    out = run(seed)
    comp = emlib.compressibility(
        [str(min(9, x["n_roots"] // 10)) for x in out["coxeter_plane"]["rings"]],
        "roots per ring on the Coxeter plane, in tens, inner ring first")
    # observer slots null: ai_interest is void
    p = emlib.write_run(NAME, seed, {"asked": ASKED, "status_before_run": "PROPOSED"},
                        out, None, None, comp, None)
    print(p)
    e, f, c, ch = out["e8"], out["fold"], out["coxeter_plane"], out["chain"]
    print("E8:", e["diagram"], "| is E8 shape", e["is_e8_shape"], "| h", e["coxeter_number"],
          "exps", e["exponents"], "| same as standard", e["same_h_and_exponents"], "| roots",
          e["n_roots"], "| norms", e["squared_lengths_in_r8"])
    print("FOLD:", {k: f[k] for k in ("distinct_folded_points", "squared_lengths_text",
                                      "roots_per_squared_length", "two_sets_of_120",
                                      "squared_length_ratio_is_phi_squared",
                                      "larger_set_is_phi_times_the_smaller_exactly")})
    print("   smaller set:", f["smaller_set"])
    print("PLANE:", c["n_rings"], "rings", [(x["radius"], x["n_roots"]) for x in c["rings"]])
    print("CHAIN: order", ch["order"], "fold", ch["exponents_on_the_fold_space"], "conjugate",
          ch["exponents_on_the_conjugate_space"], "| orbits", ch["n_orbits_of_roots"],
          ch["orbit_sizes"], "| regular", ch["every_orbit_regular_in_fold_space"],
          ch["every_orbit_regular_in_conjugate_space"], "| edge/R", ch["edge_over_radius_fold_space"],
          ch["edge_over_radius_conjugate_space"], "| logged", ch["logged_chains_at_30"])
    print("   (1, 11):", ch["chain_1_11"], "| (7, 13):", ch["chain_7_13"])


if __name__ == "__main__":
    main(sys.argv[1:])
